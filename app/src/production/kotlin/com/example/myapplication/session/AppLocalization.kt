    fun resolveEffectiveLang(selectedCode: String): String {
        return if (selectedCode.isEmpty()) {
            val sysLang = java.util.Locale.getDefault().language
            if (sysLang in listOf("en", "ja", "es")) sysLang else "ko"
        } else {
            selectedCode
        }
    }

    fun get(langCode: String, key: String): String {
        val effectiveLang = resolveEffectiveLang(langCode)
        val map = when (effectiveLang) {
            "en" -> stringsEn
            "ja" -> stringsJa
            "es" -> stringsEs
            else -> stringsKo
        }
        return map[key] ?: stringsKo[key] ?: key
    }
