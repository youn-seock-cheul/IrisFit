    fun get(langCode: String, key: String): String {
        val effectiveLang = resolveEffectiveLang(langCode)
        val translated = when (effectiveLang) {
            "en" -> stringsEn[key]
            "ja" -> stringsJa[key]
            "es" -> stringsEs[key]
            else -> stringsKo[key]
        }
        return translated ?: autoTranslate(stringsKo[key] ?: key, effectiveLang)
    }
